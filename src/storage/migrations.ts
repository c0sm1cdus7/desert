// Law (plan §15, step 7.3): a migration is a generated, committed file `src/storage/migrations/<product>.<language>.
// <from>-<to>.sql` that is never edited. Its header names both digests, the sha256 of both storage models it was planned
// from, the decisions it used and the sha256 of its body; its digest (sha256 of the whole file) is what an installation's
// migration_chain records. Raises MIGRATION_EDITED, MIGRATION_MODEL.
import { readdirSync, readFileSync } from "node:fs";
import { Value } from "@sinclair/typebox/value";
import { Type } from "@sinclair/typebox";
import { MigrationDecisionSchema, type MigrationDecision } from "./migration-decisions.ts";
import { renderModel, sha256, type StorageModel } from "./model.ts";
import type { MigrationPlan } from "./plan.ts";

export type Migration = Readonly<{
  path: string; digest: string; product: string; language: string; from: string; to: string;
  fromModel: string; toModel: string; decisions: readonly MigrationDecision[]; body: string;
}>;

export const migrationsDirectory = "src/storage/migrations/";
export const migrationPath = (product: string, language: string, from: string, to: string) =>
  `${migrationsDirectory}${product}.${language}.${from}-${to}.sql`;

export function renderMigration(from: StorageModel, to: StorageModel, plan: MigrationPlan): string {
  return [
    `-- GENERATED by \`node scripts/storage.ts plan\` from product ${to.product}, language ${to.language}. Do not edit.`,
    `-- from ${from.digest} model sha256:${sha256(renderModel(from))}`,
    `-- to ${to.digest} model sha256:${sha256(renderModel(to))}`,
    `-- decisions ${JSON.stringify(plan.decisions)}`,
    `-- body sha256:${sha256(plan.body)}`,
    "",
  ].join("\n") + plan.body;
}

const header = new RegExp([
  "^-- GENERATED by `node scripts/storage\\.ts plan` from product (?<product>[a-z0-9-]+), language (?<language>[A-Za-z0-9-]+)\\. Do not edit\\.",
  "-- from (?<from>[0-9a-f]{64}) model sha256:(?<fromModel>[0-9a-f]{64})",
  "-- to (?<to>[0-9a-f]{64}) model sha256:(?<toModel>[0-9a-f]{64})",
  "-- decisions (?<decisions>.*)",
  "-- body sha256:(?<body>[0-9a-f]{64})",
  "",
].join("\n"));

const edited = (path: string, what: string): never => {
  throw new Error(`MIGRATION_EDITED: ${path}: ${what}; a committed migration is never edited, plan a new one; contract: src/storage/migrations.ts`);
};

/** A committed migration file, checked against its own name and its recorded body digest. */
export function readMigration(path: string, text: string): Migration {
  const match = header.exec(text);
  if (!match?.groups) return edited(path, "its generated header is missing or changed");
  const { product, language, from, to, fromModel, toModel, decisions: recorded, body: bodyDigest } = match.groups as Record<string, string>;
  const body = text.slice(match[0].length);
  if (sha256(body) !== bodyDigest) edited(path, "its body differs from the body digest it was generated with");
  if (migrationPath(product!, language!, from!, to!) !== path) edited(path, "its name differs from the digests in its header");
  let decisions: unknown;
  try { decisions = JSON.parse(recorded!); } catch { return edited(path, "its decisions are not JSON"); }
  if (!Value.Check(Type.Array(MigrationDecisionSchema), decisions)) edited(path, "its decisions are not decision blocks");
  return Object.freeze({ path, digest: sha256(text), product: product!, language: language!, from: from!, to: to!,
    fromModel: fromModel!, toModel: toModel!, decisions: decisions as MigrationDecision[], body });
}

/** Every migration committed under `root` (the repository by default). */
export function readMigrations(root: URL = new URL("../../", import.meta.url)): readonly Migration[] {
  const directory = new URL(migrationsDirectory, root);
  let names: string[];
  try { names = readdirSync(directory).filter(name => name.endsWith(".sql")).sort(); } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return [];
    throw error;
  }
  return names.map(name => readMigration(`${migrationsDirectory}${name}`, readFileSync(new URL(name, directory), "utf8")));
}

let committed: readonly Migration[] | undefined;
/** The repository's committed migrations, read once per process. */
export const committedMigrations = () => committed ??= readMigrations();

/** The migrations that lead from one digest of a product to another, in order; undefined when none does. */
export function chainPath(migrations: readonly Migration[], product: string, language: string, from: string, to: string): readonly Migration[] | undefined {
  const reached = new Map<string, readonly Migration[]>([[from, []]]);
  const queue = [from];
  for (let digest = queue.shift(); digest !== undefined; digest = queue.shift()) {
    if (digest === to) return reached.get(digest);
    for (const step of migrations) {
      if (step.product !== product || step.language !== language || step.from !== digest || reached.has(step.to)) continue;
      reached.set(step.to, [...reached.get(digest)!, step]);
      queue.push(step.to);
    }
  }
  return undefined;
}

/** True when every recorded migration digest is a committed migration of the product, each starting where the previous
 * one ended, and the last one ends at `digest`. An empty chain is a fresh install of `digest`. */
export function chainLeadsTo(migrations: readonly Migration[], product: string, chain: readonly string[], digest: string): boolean {
  const steps = chain.map(entry => migrations.find(step => step.digest === entry && step.product === product));
  if (steps.some(step => step === undefined)) return false;
  const known = steps as Migration[];
  return known.every((step, position) => position === 0 ||
    (known[position - 1]!.to === step.from && known[position - 1]!.language === step.language)) &&
    (known.length === 0 || known[known.length - 1]!.to === digest);
}
