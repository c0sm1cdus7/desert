import { afterEach, expect, it } from "vitest";
import { effect } from "../facts.ts";
import { shopRig } from "../../../tests/support/shop-rig.ts";
import { contractRig } from "../../../tests/support/contract-rig.ts";
import { settle } from "../../surface/bridge/ports/house-ports.ts";
const rigs: { close(): void }[] = [];
afterEach(() => rigs.splice(0).forEach(rig => rig.close()));
const by = "assistant:beto";
it("reconstruye plan, pasos y espera; aísla dos journeys y conserva cierre", () => {
  const rig = shopRig();
  rigs.push(rig);
  for (const process of ["j1", "j2"])
    rig.bus.emit(effect("journey-opened", { goal: "Anotar", kit: [] }, by, [], process));
  rig.bus.emit(effect("journey-plan-written", { steps: [{ id: "s", text: "Preparar" }] }, by, [], "j1"));
  rig.bus.emit(effect("journey-step-done", { step: "s", note: "Preparado" }, by, [], "j1"));
  rig.bus.emit(effect("journey-waiting", { what: "Respuesta", until: 1000 }, by, [], "j1"));
  const before = rig.state().house.journeys;
  rig.restart();
  expect(rig.state().house.journeys).toEqual(before);
  expect(before.get("j2")?.steps).toEqual([]);
  rig.bus.emit(effect("journey-closed", { outcome: "done", summary: "Listo", references: [] }, by, [], "j1"));
  expect(() => rig.bus.emit(effect("journey-opened", { goal: "Otra", kit: [] }, by, [], "j1"))).toThrow();
  expect(() => rig.bus.emit(effect("journey-waiting", { what: "Tarde", until: 2000 }, by, [], "j1"))).toThrow();
  const closed = rig.state().house.journeys;
  rig.restart();
  expect(rig.state().house.journeys).toEqual(closed);
});
it("rechaza autor de identidad, proceso ausente, plan duplicado y paso ausente o repetido", () => {
  const rig = shopRig();
  rigs.push(rig);
  expect(() => rig.bus.emit(effect("journey-opened", { goal: "Anotar", kit: [] }, "beto", [], "j"))).toThrow();
  expect(() => rig.bus.emit(effect("journey-opened", { goal: "Anotar", kit: [] }, by))).toThrow();
  rig.bus.emit(effect("journey-opened", { goal: "Anotar", kit: [] }, by, [], "j"));
  const plan = effect("journey-plan-written", { steps: [{ id: "s", text: "Anotar" }] }, by, [], "j");
  rig.bus.emit(plan);
  expect(() => rig.bus.emit(plan)).toThrow();
  expect(() => rig.bus.emit(effect("journey-step-done", { step: "otro", note: "No" }, by, [], "j"))).toThrow();
  const done = effect("journey-step-done", { step: "s", note: "Sí" }, by, [], "j");
  rig.bus.emit(done);
  expect(() => rig.bus.emit(done)).toThrow();
  expect(() => rig.bus.emit(effect("journey-waiting", { what: "Ajena", until: 1 }, "mind:sales", [], "j"))).toThrow();
});
it("la ejecución fija actor y proceso, conserva anidados y rechaza un journey cerrado o ajeno", async () => {
  const rig = contractRig();
  rigs.push(rig);
  rig.bus.emit(effect("assistant-enabled", { owner: "beto", name: "Nora" }, "ana"));
  const kit = [{ tool: "desk", acts: ["nested", "open", "say"] }];
  rig.bus.emit(effect("assistant-kit-set", { owner: "beto", kit }, "beto"));
  rig.bus.emit(effect("mind-card-assigned", { mind: by, card: "test", version: "v1", capabilities: [] }, "ana"));
  const opened = rig.bus.emit(effect("journey-opened", { goal: "Abrir", kit }, by, [], "j"));
  const started = rig.tools().act({ target: "desk", act: "nested", input: {} }, 0, by, [opened.id]);
  expect((await settle(started)).status).toBe("accepted");
  const acts = rig.facts().filter(event => event.kind === "act" && event.by === by);
  expect(acts).toHaveLength(2);
  expect(acts.every(event => event.process === "j")).toBe(true);
  expect(rig.tools().act({ target: "desk", act: "say", input: {} }, 0, "ana", [opened.id]).status).toBe("rejected");
  rig.bus.emit(effect("journey-closed", { outcome: "done", summary: "Listo", references: [] }, by, [], "j"));
  expect(rig.tools().act({ target: "desk", act: "say", input: {} }, 0, by, [opened.id]).status).toBe("rejected");
});
