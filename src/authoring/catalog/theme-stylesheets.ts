// The generated block of theme.css: the one Tailwind compile loads every stylesheet a declaration lists (a mechanism's
// `files`, a piece's `owner.parts`), so the list is a projection of the declarations, written by
// `node scripts/catalog.ts --write` and compared by rules C and G. Mechanisms come first, then pieces, each by id, its
// stylesheets in the order its declaration lists them. The theme mechanism's own stylesheets (its tokens and base) are the
// theme entry's, written around the block by hand.
import { posix } from "node:path";
import type { LocatedDeclaration } from "./gate/inventory.ts";
import { themeMechanism } from "./layout.ts";

export const themeBlockBegin = "/* The stylesheets the catalog declarations list, generated by `node scripts/catalog.ts --write`; do not edit. */";
export const themeBlockEnd = "/* End of the generated stylesheets. */";

const byId = (left: LocatedDeclaration, right: LocatedDeclaration) => left.declaration.id < right.declaration.id ? -1 : 1;
const isStylesheet = (name: string) => name.endsWith(".css");

/** Every stylesheet a declaration lists, as repository paths, in the block's order. */
export function declaredStylesheets(declarations: readonly LocatedDeclaration[]): string[] {
  const at = (path: string, name: string) => posix.join(posix.dirname(path), name);
  const sorted = [...declarations].sort(byId);
  const mechanisms = sorted.flatMap(({ path, declaration }) => declaration.kind === "mechanism" && declaration.id !== themeMechanism
    ? declaration.files.filter(isStylesheet).map(name => at(path, name)) : []);
  const pieces = sorted.flatMap(({ path, declaration }) => declaration.kind === "mechanism" ? []
    : (declaration.owner.parts ?? []).filter(isStylesheet).map(name => at(path, name)));
  return [...mechanisms, ...pieces];
}

/** The block's lines (without its markers): one import per declared stylesheet, relative to the theme entry. */
export function themeStylesheetImports(declarations: readonly LocatedDeclaration[], theme: string): string[] {
  return declaredStylesheets(declarations).map(path => `@import "./${posix.relative(posix.dirname(theme), path)}";`);
}

/** Where the block is in a theme entry's text: the 0-based lines of its two markers, when both are present once, in order. */
export function themeBlock(text: string): Readonly<{ begin: number; end: number; lines: readonly string[] }> | undefined {
  const lines = text.split("\n"), begin = lines.indexOf(themeBlockBegin), end = lines.indexOf(themeBlockEnd);
  const once = (marker: string) => lines.filter(line => line === marker).length === 1;
  return begin >= 0 && end > begin && once(themeBlockBegin) && once(themeBlockEnd) ? { begin, end, lines: lines.slice(begin + 1, end) } : undefined;
}

/** The theme entry with its block regenerated; a text without a block gets one after its last import. */
export function withThemeStylesheets(text: string, imports: readonly string[]): string {
  const lines = text.split("\n"), block = themeBlock(text);
  if (block) return [...lines.slice(0, block.begin + 1), ...imports, ...lines.slice(block.end)].join("\n");
  const last = lines.reduce((found, line, index) => line.startsWith("@import ") ? index : found, -1);
  return [...lines.slice(0, last + 1), themeBlockBegin, ...imports, themeBlockEnd, ...lines.slice(last + 1)].join("\n");
}
