import type { VisualInventory } from "./inventory.ts";

export function renderVisualInventory(report: VisualInventory): string {
  const sources = report.sources;
  const findings = sources.flatMap(item => item.findings);
  const counts = new Map<string, number>();
  for (const item of findings) counts.set(item.code, (counts.get(item.code) ?? 0) + 1);
  return `# Visual ownership source inventory\n\nGenerated by \`node scripts/check-visual-boundary.ts --write-audit\`.\n` +
    `This is unresolved migration evidence, **not approval or a passing ownership gate**.\n\n` +
    `Source digest: \`${report.sourceDigest}\`.\n\n` +
    `${sources.length} inventoried files; ${sources.filter(item => item.path.startsWith("src/svelte/")).length} in \`src/svelte\`; ` +
    `${findings.length} detected findings in ${sources.filter(item => item.findings.length).length} files.\n` +
    `These are syntactic findings, not ${findings.length} distinct bugs or an exhaustive semantic override count.\n\n` +
    `## Detected boundaries\n\n| Rule | Findings |\n| --- | ---: |\n` +
    [...counts].sort().map(([code, count]) => `| ${code} | ${count} |`).join("\n") +
    `\n\n## Qualification gaps\n\n` + report.limitations.map(value => `- ${value}`).join("\n") +
    `\n\n## Exhaustive source classification\n\nCandidate owners are investigation assignments, not exemptions. ` +
    `Vendor private parts and shared CSS are included even when not reached by a preview.\n\n` +
    `| Source | Responsibility | Candidate owner | Findings |\n| --- | --- | --- | ---: |\n` +
    sources.map(source => `| \`${source.path}\` | ${source.role} | ${source.owner} | ${source.findings.length} |`).join("\n") +
    `\n\n## Concrete unresolved occurrences\n\n` + sources.filter(source => source.findings.length).map(source =>
      `### ${source.path}\n\n` + source.findings.map(item =>
        `- Line ${item.line}: \`${item.code}\` — \`${item.operation.replace(/\s+/g, " ").replaceAll("`", "'").slice(0, 160)}\``).join("\n")).join("\n\n") + "\n";
}
