import assert from "node:assert/strict";
import { after, before, test } from "node:test";
import { compile } from "../src/compile.ts";
import { openLocalController } from "../src/local/controller.ts";
import { viewProgramActivities } from "../src/activities/presentation.ts";
import { localViewProgram } from "../src/local/view-program.ts";
import { ActivityNotebook, guidedProgram } from "./fixtures/activity-experience.ts";
import { postgresCluster } from "./fixtures/postgres.ts";
import { captureViewEvents } from "./fixtures/owned-view-events.ts";
import { until } from "./fixtures/multi-view-runtime.ts";
import { transientFrame } from "../src/interaction/transient-frame.ts";

let cluster: ReturnType<typeof postgresCluster>;
before(() => { cluster = postgresCluster(); });
after(() => cluster.dispose());

test("guided writing uses shared Form panels, durable steps, Back invalidation and explicit canonical acceptance", async t => {
  const application = compile(ActivityNotebook), activities = viewProgramActivities(application, guidedProgram, "human");
  assert.ok(activities);
  const host = await openLocalController(application, { ...await cluster.database(), roles: ["notes"], activities });
  t.after(() => host.close());
  const identity = await host.identities.issue("Guided writer"), session = host.connect(identity.token, "human");
  const expected = { id: "human", contractDigest: application.digest };
  let model = localViewProgram(session, guidedProgram, expected);
  t.after(() => model.stop());
  const emit = () => captureViewEvents(model);
  const next = () => emit()({ kind: "surface.invoke", intent: { kind: "journey", journey: "create-note" } });
  async function open() {
    await model.start();
    await until(() => model.snapshot().state.availability.journeys["create-note"]?.dependenciesReady === true);
    model.navigate("notes");
    await until(() => !model.snapshot().resolved.disabledOutputs.includes("create"));
    emit()({ kind: "surface.invoke", intent: { kind: "view.output", view: "notes", output: "create" } });
    await until(() => !model.snapshot().activity.busy);
    assert.equal(model.snapshot().error, null);
    assert.ok(model.snapshot().activity.activity);
  }
  await open();
  const first = model.snapshot().panel!.frame;
  assert.equal(first.top.title, "Name your note");
  assert.equal(first.content.kind, "form");
  assert.equal(transientFrame(first, false).top.leading?.intent.kind, "close");
  if (first.content.kind === "form") assert.deepEqual(first.content.fields.map(field => field.name), ["title"]);
  assert.equal(first.bottom.primary?.state, "unavailable", "step validation comes from the canonical command constraints");
  assert.throws(() => emit()({ kind: "input.change", name: "body", value: "Bypass" }), /INVALID_VIEW_INPUT/);
  emit()({ kind: "input.change", name: "title", value: "Guided title" });
  assert.equal(model.snapshot().panel!.frame.bottom.primary?.state, "ready");
  const oldStep = emit(); next();
  await until(() => model.snapshot().activity.activity?.progress.nextStep === 1 && !model.snapshot().activity.busy);
  const second = transientFrame(model.snapshot().panel!.frame, false);
  assert.equal(second.top.leading?.intent.kind, "back");
  assert.deepEqual(second.top.leading, second.bottom.secondary);
  oldStep({ kind: "input.change", name: "body", value: "Stale owner" });
  assert.equal(model.snapshot().activity.draft.body, "");
  const id = model.snapshot().activity.activity!.id;
  model.stop(); model = localViewProgram(session, guidedProgram, expected); await open();
  assert.equal(model.snapshot().activity.activity!.id, id, "server discovery resumes the same private activity");
  assert.equal(model.snapshot().activity.activity!.progress.input.title, "Guided title");
  emit()({ kind: "input.change", name: "body", value: "Saved in step two" }); next();
  await until(() => Boolean(model.snapshot().activity.prepared) && !model.snapshot().activity.busy);
  const firstIntent = model.snapshot().activity.prepared!;
  assert.equal(model.snapshot().panel?.frame.content.kind, "review");
  const review = transientFrame(model.snapshot().panel!.frame, false);
  assert.equal(review.top.leading?.intent.kind, "back");
  assert.deepEqual(review.top.leading, review.bottom.secondary);
  assert.deepEqual(await session.read((await session.begin("read-note")).id), []);
  emit()({ kind: "surface.invoke", intent: { kind: "back" } });
  await until(() => model.snapshot().activity.activity?.progress.nextStep === 1 && !model.snapshot().activity.busy);
  assert.equal(model.snapshot().activity.draft.body, "Saved in step two");
  await assert.rejects(session.accept(firstIntent.id, firstIntent.confirmationDigest), /ACTIVITY_PREPARATION_INVALIDATED/);
  emit()({ kind: "input.change", name: "body", value: "Revised after Back" }); next();
  await until(() => Boolean(model.snapshot().activity.prepared) && !model.snapshot().activity.busy);
  emit()({ kind: "surface.invoke", intent: { kind: "accept" } });
  await until(() => model.snapshot().state.detail?.facts.body === "Revised after Back");
  assert.equal(model.snapshot().activity.experience, null);
  const records = await session.read((await session.begin("read-note")).id);
  assert.equal(records.length, 1);
  assert.equal(records[0]?.facts.title, "Guided title");
});
