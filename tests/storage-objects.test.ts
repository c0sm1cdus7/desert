const root = new URL("../", import.meta.url);
const rejects = (code: string, run: () => unknown) =>
  assert.throws(run, (error: unknown) => error instanceof Error && error.message.startsWith(`${code}: `));
const owned = (objects: ProductDefinition["objects"]) =>
  product({ id: "case-product", objects, policies: objects.map(object => ({ kind: "ownership" as const, object: object.id, field: "owner" })) });
const storageOf = (definition: unknown) => objectStorage(definition, SpanishClient);
const language = `COLLATE "product_storage_kinds"."desert_language"`;

const taskTable = `CREATE TABLE IF NOT EXISTS "product_storage_kinds"."task" (
  "id" uuid NOT NULL,
  "version" integer NOT NULL CHECK ("version" > 0),
  "due_note" text ${language} NOT NULL CHECK (char_length("due_note") <= 3),
  "estimate" bigint NOT NULL CHECK ("estimate" BETWEEN -9007199254740991 AND 9007199254740991),
  "owner" uuid NOT NULL,
  "priority" bigint NOT NULL CHECK ("priority" BETWEEN 1 AND 5),
  "recording" uuid NOT NULL,
  "state" text NOT NULL CHECK ("state" IN ('active', 'trashed')),
  "status" text NOT NULL CHECK ("status" IN ('open', 'done')),
  "tags" text[] ${language} NOT NULL CHECK ("product_storage_kinds"."desert_labels_valid"("tags", 2, 5)),
  "title" text ${language} NOT NULL CHECK (char_length("title") BETWEEN 1 AND 8),
  PRIMARY KEY ("id"),
  FOREIGN KEY ("owner") REFERENCES "desert_identities" ("id"),
  FOREIGN KEY ("recording") REFERENCES "product_storage_kinds"."asset" ("id")
);
CREATE INDEX IF NOT EXISTS "task_by_owner" ON "product_storage_kinds"."task" ("owner");
`;
const projectsJoin = `CREATE TABLE IF NOT EXISTS "product_storage_kinds"."task_projects" (
  "object_id" uuid NOT NULL,
  "target_id" uuid NOT NULL,
  "position" integer NOT NULL CHECK ("position" >= 0),
  PRIMARY KEY ("object_id", "target_id"),
  UNIQUE ("object_id", "position"),
  FOREIGN KEY ("object_id") REFERENCES "product_storage_kinds"."task" ("id"),
  FOREIGN KEY ("target_id") REFERENCES "product_storage_kinds"."project" ("id")
);
CREATE INDEX IF NOT EXISTS "task_projects_by_target" ON "product_storage_kinds"."task_projects" ("target_id");
`;

test("STORAGE_DERIVATION: every stored installation's product has its committed DDL file, named by language and digest, equal to the generator", async () => {
  assert.ok(storedInstallations.length > 0);
  for (const { installation, products } of storedInstallations) {
    for (const definition of products) {
      const path = objectDdlPath(definition, installation);
      assert.equal(path, `src/storage/generated/${definition.id}.${installation.language}.${compile(definition).digest}.sql`);
      assert.equal(await readFile(new URL(path, root), "utf8"), renderObjectDdl(definition, installation));
    }
  }
});

test("7.1 control: each fact kind maps to the column the plan's table names (text, bigint, enum, principal, file, labels)", () => {
  const ddl = renderObjectDdl(StorageKinds, SpanishClient);
  assert.ok(ddl.startsWith(`-- GENERATED by src/storage/ddl.ts from product storage-kinds, language es, installation digest ${compile(StorageKinds).digest}. Do not edit.\n`));
  assert.ok(ddl.includes(taskTable), "task table");
  assert.ok(ddl.includes(projectsJoin), "references → join table with FKs on both sides");
  assert.ok(ddl.includes(`CREATE CONSTRAINT TRIGGER "task_projects_object_id_limit" AFTER INSERT OR UPDATE ON "product_storage_kinds"."task_projects" NOT DEFERRABLE FOR EACH ROW EXECUTE FUNCTION "product_storage_kinds"."task_projects_object_id_limit"();\n`));
  assert.ok(ddl.includes(`IF (SELECT count(*) FROM "product_storage_kinds"."task_projects" WHERE "object_id" = NEW."object_id") > 12 THEN`));
  assert.ok(ddl.includes(`IF (SELECT count(*) FROM "product_storage_kinds"."photo_album_cover" WHERE "object_id" = NEW."object_id") > 1 THEN`));
  assert.ok(ddl.includes(`  UNIQUE ("owner", "name"),\n`), "declared uniqueness");
});

test("7.1 control: one object table per object type in declaration order, then one join table per reference fact; columns follow the canonical (sorted) facts", () => {
  const storage = storageOf(StorageKinds);
  assert.equal(storage.namespace, "product_storage_kinds");
  // A product with a file fact holds the SDK's asset object first (plan §15, step 7.4; src/assets/object.ts).
  assert.deepEqual(storage.tables.map(table => table.qualifiedName), [
    "product_storage_kinds.asset", "product_storage_kinds.project", "product_storage_kinds.photo_album", "product_storage_kinds.album_photo",
    "product_storage_kinds.task", "product_storage_kinds.asset_renditions", "product_storage_kinds.photo_album_cover",
    "product_storage_kinds.album_photo_albums", "product_storage_kinds.task_projects",
  ]);
  assert.deepEqual(storage.tables.map(table => table.columns.map(column => column.name)).slice(0, 3),
    [["id", "version", "digest", "duration", "height", "media_type", "owner", "size", "state", "width"],
      ["id", "version", "color", "name", "owner"], ["id", "version", "owner", "title"]]);
  assert.deepEqual(storage.objects.map(object => [object.id, object.table.name]),
    [["asset", "asset"], ["project", "project"], ["photo-album", "photo_album"], ["album-photo", "album_photo"], ["task", "task"]]);
});

test("Q1: every scalar fact is one typed column of its own kind; no object table holds jsonb", () => {
  for (const { installation, products } of [...storedInstallations, { installation: SpanishClient, products: [StorageKinds] }]) {
    for (const definition of products) {
      for (const { table } of objectStorage(definition, installation).objects) {
        assert.deepEqual(table.columns.filter(entry => entry.storage.type === "jsonb").map(entry => entry.name), [], table.qualifiedName);
      }
    }
  }
  const task = storageOf(StorageKinds).tables.find(table => table.name === "task");
  assert.deepEqual(task?.columns.map(entry => [entry.name, entry.storage.type]), [["id", "uuid"], ["version", "integer"], ["due_note", "text"],
    ["estimate", "bigint"], ["owner", "uuid"], ["priority", "bigint"], ["recording", "uuid"], ["state", "text"], ["status", "text"],
    ["tags", "text[]"], ["title", "text"]]);
});

test("Q1 negative: a free JSON drawer is neither declarable as a fact nor storable as a fact column", () => {
  const drawer = { id: "case", facts: { owner: { kind: "principal" }, extras: { kind: "json" } } };
  assert.throws(() => compile({ id: "case-product", objects: [drawer], policies: [{ kind: "ownership", object: "case", field: "owner" }] }),
    /^Error: Invalid definition/);
  rejects("STORAGE_DECLARATION", () => factColumn("case.extras", column.json(column.text())));
  assert.equal(readColumnStorage(factColumn("case.title", column.text()), "case.title").type, "text", "control: a typed column passes");
});

test("one Postgres schema per product inside the client's database, from the one namespace function", () => {
  assert.equal(productNamespace("storage-kinds"), "product_storage_kinds");
  for (const table of storageOf(StorageKinds).tables) assert.equal(table.namespace, productNamespace("storage-kinds"));
});

test("STORAGE_DECLARATION: two facts that map to one column name are rejected", () => {
  const Case = objectType({ id: "case", facts: { dueNote: text(), due_note: text(), owner: principal() } });
  rejects("STORAGE_DECLARATION", () => storageOf(owned([Case])));
});

test("STORAGE_DECLARATION: a fact named like a generated column (id, version) is rejected", () => {
  rejects("STORAGE_DECLARATION", () => storageOf(owned([objectType({ id: "case", facts: { version: text(), owner: principal() } })])));
  rejects("STORAGE_DECLARATION", () => storageOf(owned([objectType({ id: "case", facts: { id: text(), owner: principal() } })])));
});

test("STORAGE_DECLARATION: a join table whose name is already an object table is rejected", () => {
  const Tag = objectType({ id: "tag", facts: { name: text(), color: enumeration(["blue"]), owner: principal() } });
  const Case = objectType({ id: "case", facts: { tags: references(Tag, { label: "name", color: "color" }), owner: principal() } });
  const Clash = objectType({ id: "case-tags", facts: { title: text(), owner: principal() } });
  rejects("STORAGE_DECLARATION", () => storageOf(owned([Tag, Case, Clash])));
});

test("STORAGE_DECLARATION: an object id longer than a Postgres identifier is rejected", () => {
  rejects("STORAGE_DECLARATION", () => storageOf(owned([objectType({ id: "o".repeat(64), facts: { owner: principal() } })])));
});

test("unique: a declared unique set must name scalar facts of the object", () => {
  const unknown = objectType({ id: "case", unique: [["missing"]], facts: { title: text(), owner: principal() } });
  assert.throws(() => compile(owned([unknown])), /INVALID_UNIQUE_DECLARATION/);
  const listed = objectType({ id: "case", unique: [["tags"]], facts: { tags: labels(), owner: principal() } });
  assert.throws(() => compile(owned([listed])), /INVALID_UNIQUE_DECLARATION/);
  const valid = objectType({ id: "case", unique: [["owner", "title"]], facts: { title: text(), owner: principal() } });
  assert.equal(compile(owned([valid])).id, "case-product");
  assert.equal(ownershipPolicy(valid, "owner").field, "owner");
});
