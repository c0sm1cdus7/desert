test("STORAGE_DERIVATION: every stored product has its committed DDL file, named by installation digest, equal to the generator", async () => {
  assert.ok(storedProducts.length > 0);
  for (const definition of storedProducts) {
    const path = objectDdlPath(definition);
    assert.equal(path, `src/storage/generated/${definition.id}.${compile(definition).digest}.sql`);
    assert.equal(await readFile(new URL(path, root), "utf8"), renderObjectDdl(definition));
  }
});

test("7.1 control: each fact kind maps to the column the plan's table names (text, bigint, enum, principal, asset, labels)", () => {
  const ddl = renderObjectDdl(StorageKinds);
  assert.ok(ddl.startsWith(`-- GENERATED by src/storage/ddl.ts from product storage-kinds, installation digest ${compile(StorageKinds).digest}. Do not edit.\n`));
  assert.ok(ddl.includes(taskTable), "task table");
  assert.ok(ddl.includes(projectsJoin), "references → join table with FKs on both sides");
  assert.ok(ddl.includes(`CREATE CONSTRAINT TRIGGER "task_projects_object_id_limit" AFTER INSERT OR UPDATE ON "product_storage_kinds"."task_projects" NOT DEFERRABLE FOR EACH ROW EXECUTE FUNCTION "product_storage_kinds"."task_projects_object_id_limit"();\n`));
  assert.ok(ddl.includes(`IF (SELECT count(*) FROM "product_storage_kinds"."task_projects" WHERE "object_id" = NEW."object_id") > 12 THEN`));
  assert.ok(ddl.includes(`IF (SELECT count(*) FROM "product_storage_kinds"."photo_album_cover" WHERE "object_id" = NEW."object_id") > 1 THEN`));
  assert.ok(ddl.includes(`  UNIQUE ("owner", "name"),\n`), "declared uniqueness");
  assert.ok(!ddl.includes("jsonb"), "no jsonb extras column (sparse facts assumption)");
});

test("7.1 control: one object table per object type in declaration order, then one join table per reference fact; columns follow the canonical (sorted) facts", () => {
  const storage = objectStorage(StorageKinds);
  assert.equal(storage.namespace, "product_storage_kinds");
  assert.deepEqual(storage.tables.map(table => table.qualifiedName), [
    "product_storage_kinds.project", "product_storage_kinds.photo_album", "product_storage_kinds.album_photo", "product_storage_kinds.task",
    "product_storage_kinds.photo_album_cover", "product_storage_kinds.album_photo_albums", "product_storage_kinds.task_projects",
  ]);
  assert.deepEqual(storage.tables.map(table => table.columns.map(column => column.name)).slice(0, 2),
    [["id", "version", "color", "name", "owner"], ["id", "version", "owner", "title"]]);
});

test("assumptions: the four §15 owner questions are answered in one block and tenancy is one function", () => {
  assert.deepEqual(storageAssumptions, { sparseFacts: "typed-nullable-columns", trash: "state-fact",
    commands: "one-object-per-command", tenancy: "schema-per-product" });
  assert.equal(productNamespace("storage-kinds"), "product_storage_kinds");
  for (const table of objectStorage(StorageKinds).tables) assert.equal(table.namespace, productNamespace("storage-kinds"));
  // Q1: a sparse fact is a nullable typed column; a carried fact stays NOT NULL.
  assert.equal(readColumnStorage(factColumn(column.boundedText({ maxLength: 3 }), true), "sparse").nullable, true);
  assert.equal(readColumnStorage(factColumn(column.boundedText({ maxLength: 3 }), false), "carried").nullable, false);
  // Q2: rows are never deleted, so nothing cascades; Q3: constraints hold at each statement.
  const ddl = renderObjectDdl(StorageKinds);
  assert.equal(ddl.includes("ON DELETE"), false);
  assert.equal(ddl.includes(" DEFERRABLE INITIALLY DEFERRED"), false);
  assert.equal(constraintTiming(), "immediate");
});

test("STORAGE_DECLARATION: two facts that map to one column name are rejected", () => {
  const Case = objectType({ id: "case", facts: { dueNote: text(), due_note: text(), owner: principal() } });
  rejects("STORAGE_DECLARATION", () => objectStorage(owned([Case])));
});

test("STORAGE_DECLARATION: a fact named like a generated column (id, version) is rejected", () => {
  rejects("STORAGE_DECLARATION", () => objectStorage(owned([objectType({ id: "case", facts: { version: text(), owner: principal() } })])));
  rejects("STORAGE_DECLARATION", () => objectStorage(owned([objectType({ id: "case", facts: { id: text(), owner: principal() } })])));
});

test("STORAGE_DECLARATION: a join table whose name is already an object table is rejected", () => {
  const Tag = objectType({ id: "tag", facts: { name: text(), color: enumeration(["blue"]), owner: principal() } });
  const Case = objectType({ id: "case", facts: { tags: references(Tag, { label: "name", color: "color" }), owner: principal() } });
  const Clash = objectType({ id: "case-tags", facts: { title: text(), owner: principal() } });
  rejects("STORAGE_DECLARATION", () => objectStorage(owned([Tag, Case, Clash])));
});

test("STORAGE_DECLARATION: an object id longer than a Postgres identifier is rejected", () => {
  rejects("STORAGE_DECLARATION", () => objectStorage(owned([objectType({ id: "o".repeat(64), facts: { owner: principal() } })])));
});

test("unique: a declared unique set must name scalar facts of the object", () => {
  const unknown = objectType({ id: "case", unique: [["missing"]], facts: { title: text(), owner: principal() } });
  assert.throws(() => compile(owned([unknown])), /INVALID_UNIQUE_DECLARATION/);
  const listed = objectType({ id: "case", unique: [["tags"]], facts: { tags: labels(), owner: principal() } });
  assert.throws(() => compile(owned([listed])), /INVALID_UNIQUE_DECLARATION/);
  const valid = objectType({ id: "case", unique: [["owner", "title"]], facts: { title: text(), owner: principal() } });
  assert.equal(compile(owned([valid])).id, "case-product");
  assert.equal(ownershipPolicy(valid, "owner").field, "owner");
});

test("UNIQUE_NOT_YET_ENFORCED: the local controller refuses a product that declares unique facts until objects live in typed tables", async () => {
  const [memo, ...others] = SharedProduct.objects;
  const declared = { ...SharedProduct, objects: [{ ...memo, unique: [["title"]] }, ...others] };
  const options = { socketDirectory: "/nonexistent", database: "none", user: "none", roles: ["workspace"] };
  await assert.rejects(openLocalController(compile(declared), options), /^Error: UNIQUE_NOT_YET_ENFORCED: memo: /);
  // Control: without the declaration the guard passes and opening fails later, at the socket.
  await assert.rejects(openLocalController(compile(SharedProduct), options), /^Error: ENOENT/);
});
